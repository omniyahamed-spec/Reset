// Runs before every build: stamps a build id into the app and into
// public/version.json, so open apps can tell when a newer version is live.
const fs = require("fs");
const path = require("path");
const id = (process.env.VERCEL_GIT_COMMIT_SHA || String(Date.now())).slice(0, 12);
fs.writeFileSync(path.join(__dirname, "..", "public", "version.json"), JSON.stringify({ id }) + "\n");
fs.writeFileSync(
  path.join(__dirname, "..", "src", "buildId.ts"),
  `// Generated by scripts/stamp-version.js at build time. Do not edit.\nexport const BUILD_ID: string = ${JSON.stringify(id)};\n`
);
console.log("Build id:", id);
